// Command genshadowed regenerates internal/preflight/shadowed_names.go, the
// list of identifiers an inline `on*=` handler resolves against the DOM before
// window, from a real browser engine — so the list tracks whatever Chromium
// actually exposes rather than a hand-kept guess.
//
// Run this in a Chromium DevTools console on any page (about:blank works) and
// save the printed JSON array:
//
//	(() => {
//	  const set = new Set();
//	  const protos = [EventTarget.prototype, Node.prototype, Element.prototype,
//	    HTMLElement.prototype, Document.prototype, HTMLDocument.prototype,
//	    HTMLFormElement.prototype];
//	  for (const tag of ["a", "button", "input", "select", "textarea", "form", "div",
//	      "span", "img", "table", "td", "details", "summary", "label", "option",
//	      "canvas", "svg"]) {
//	    const el = document.createElement(tag);
//	    for (let o = Object.getPrototypeOf(el); o && o !== Object.prototype; o = Object.getPrototypeOf(o)) protos.push(o);
//	  }
//	  for (const proto of protos) for (const k of Object.getOwnPropertyNames(proto)) set.add(k);
//	  return JSON.stringify([...set].filter((n) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(n) && !/^on[a-z]/.test(n) && n !== "constructor").sort());
//	})()
//
// then, from the repository root:
//
//	go run ./internal/preflight/internal/genshadowed -in names.json
//
// The input may also be any file of double-quoted names (the old
// lib/preflight-shadowed-names.js was converted that way). The filtering above
// is applied again here, so a raw dump is fine.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"slices"
	"strings"
)

var (
	quoted     = regexp.MustCompile(`"([A-Za-z_$][A-Za-z0-9_$]*)"`)
	identifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)
	handler    = regexp.MustCompile(`^on[a-z]`)
)

func main() {
	in := flag.String("in", "", "JSON array (or any file of double-quoted names) to read")
	out := flag.String("out", "internal/preflight/shadowed_names.go", "Go file to write")
	flag.Parse()
	if *in == "" {
		fmt.Fprintln(os.Stderr, "genshadowed: -in is required")
		os.Exit(2)
	}
	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "genshadowed:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	src, err := os.ReadFile(in)
	if err != nil {
		return err
	}
	seen := map[string]bool{}
	var names []string
	for _, m := range quoted.FindAllSubmatch(src, -1) {
		n := string(m[1])
		// `on*` names are the browser's own handler slots, not plausible author globals.
		if seen[n] || !identifier.MatchString(n) || handler.MatchString(n) || n == "constructor" {
			continue
		}
		seen[n] = true
		names = append(names, n)
	}
	if len(names) == 0 {
		return fmt.Errorf("no names found in %s", in)
	}
	slices.Sort(names)

	var b bytes.Buffer
	b.WriteString(`// SPDX-License-Identifier: BUSL-1.1
// Copyright (c) 2026 ElcanoTek, Inc.

// Code generated by internal/preflight/internal/genshadowed; DO NOT EDIT.

package preflight

// shadowedNames is every property reachable on the objects an inline ` + "`on*=`" + `
// handler puts on its scope chain: the element -> its form owner -> the
// document -> window. A bare identifier in such a handler resolves against
// those FIRST, so a page that defines ` + "`function togglePopover()`" + ` and writes
// ` + "`onclick=\"togglePopover()\"`" + ` calls HTMLElement.prototype.togglePopover instead
// and throws NotSupportedError. That exact collision silently killed the
// date-range picker on a live dashboard.
var shadowedNames = map[string]struct{}{
`)
	line := ""
	for _, n := range names {
		tok := fmt.Sprintf("%q: {}, ", n)
		if len(line)+len(tok) > 90 {
			b.WriteString("\t" + strings.TrimSpace(line) + "\n")
			line = ""
		}
		line += tok
	}
	if line != "" {
		b.WriteString("\t" + strings.TrimSpace(line) + "\n")
	}
	b.WriteString("}\n")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	if err := os.WriteFile(out, formatted, 0o644); err != nil { //nolint:gosec // generated source is world-readable like any other
		return err
	}
	fmt.Printf("wrote %d names to %s\n", len(names), out)
	return nil
}
